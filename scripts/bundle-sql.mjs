// Concatenates every migration into one file for the Supabase SQL Editor: supabase/bundle/schema.sql
// (Alternative: `supabase db push` with the Supabase CLI.) Usage: node scripts/bundle-sql.mjs
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
const files = readdirSync("supabase/migrations").filter((f) => f.endsWith(".sql")).sort();
const out = files.map((f) => `-- ===== ${f} =====\n${readFileSync(`supabase/migrations/${f}`, "utf8")}`).join("\n\n");
mkdirSync("supabase/bundle", { recursive: true });
writeFileSync("supabase/bundle/schema.sql", `-- Generated by scripts/bundle-sql.mjs — do not edit. ${files.length} migrations.\n\n${out}\n`);
console.log(`supabase/bundle/schema.sql (${files.length} migrations, ${(out.length / 1024).toFixed(0)} KB)`);
